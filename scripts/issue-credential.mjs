#!/usr/bin/env node
/**
 * Issue one conformance attestation credential - the locked half of the
 * two-channel issuance flow. The human act is approving the protected
 * `conformance-issuance` workflow run (.github/workflows/issue-credential.yml);
 * this script turns that approval into signed, committed artifacts, and
 * REFUSES anything the approval could not have meant:
 *
 *   fail closed on: unprovisioned program keys; an env private key whose
 *   public half is not in registry/keys/program-keys.json; a slug without a
 *   registry entry; an entry not at status in-verification; any mismatch
 *   between the workflow inputs and the entry's claimed level / scope /
 *   categories / suiteVersion; a duplicate issuance (the deterministic id
 *   already committed); allocation-ledger inconsistency; a status list whose
 *   current proof does not verify; and finally the full site build - which
 *   re-verifies everything cryptographically - failing on the result.
 *
 * What it writes (all committed by the workflow's PR - the human-auditable
 * issuance record):
 *   registry/credentials/<id32>.json          the signed credential
 *   registry/credentials/status/*.json        both status lists, rebuilt and
 *                                             re-signed (bits preserved)
 *   registry/credentials/allocations.json     the ledger, +1 allocation
 *   registry/builders/<slug>.json             status -> verified + attestationUrl
 *   workers/badge/generated-allowlist.mjs     regenerated by the site build
 *
 * Keys arrive ONLY via env (K_ISSUER_PRIVATE, K_STATUS_PRIVATE - the
 * environment secrets); they are never written anywhere. Run locally only
 * against a throwaway registry (the e2e test does exactly that).
 *
 * Usage: node scripts/issue-credential.mjs --slug S --subject-id URL_OR_DID
 *   --impl-name N --impl-version V --git-commit SHA40 --level L1|L2|L3
 *   --scope full|subset [--categories a,b] --package-version SEMVER
 *   --verdict-url URL [--impl-repo URL] [--summary PATH] [--pr-body PATH]
 * (--impl-repo defaults to the entry's repo field; GitHub's 10-input
 * workflow_dispatch cap is why it is not a workflow input.)
 */
import { spawnSync } from "node:child_process";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { parseArgs } from "node:util";
import {
  CREDENTIALS_BASE,
  ISSUER_DID,
  STATUS_LIST_BITS,
  STATUS_LIST_BYTES,
  STATUS_PURPOSES,
  buildCredential,
  buildStatusListCredential,
  decodeStatusList,
  encodeStatusList,
  signCredential,
  verifyCredential,
  verifyStatusListAgainstCommittedKey,
} from "./lib/attest.mjs";
import { decodePrivateKeyMultibase, encodePublicKeyMultibase, publicRawFromSeed } from "./lib/keys.mjs";
import { validateRegistry } from "./validate.mjs";

const here = dirname(fileURLToPath(import.meta.url));
const repoRoot = join(here, "..");
const rel = (...parts) => join(repoRoot, ...parts);

const fail = (message) => {
  console.error(`issue-credential: ${message}`);
  process.exit(1);
};

const { values: args } = parseArgs({
  options: {
    slug: { type: "string" },
    "subject-id": { type: "string" },
    "impl-name": { type: "string" },
    "impl-version": { type: "string" },
    "impl-repo": { type: "string" },
    "git-commit": { type: "string" },
    level: { type: "string" },
    scope: { type: "string" },
    categories: { type: "string" },
    "package-version": { type: "string" },
    "verdict-url": { type: "string" },
    summary: { type: "string" },
    "pr-body": { type: "string" },
  },
});
for (const required of ["slug", "subject-id", "impl-name", "impl-version", "git-commit", "level", "scope", "package-version", "verdict-url"]) {
  if (args[required] === undefined || args[required] === "") fail(`--${required} is required`);
}
if (!/^https:\/\//.test(args["verdict-url"])) fail("--verdict-url must be an https URL (the public verdict thread)");

// ── keys: env privates must match the committed publics ─────────────────────
const { programKeys, errors: preErrors } = validateRegistry();
if (preErrors.length > 0) fail(`the registry must validate before issuance:\n  - ${preErrors.join("\n  - ")}`);
if (!programKeys.provisioned) fail("program keys are unprovisioned (registry/keys/program-keys.json is the sentinel) - run the key ceremony first");

function matchKey(envName, purpose) {
  const multibase = process.env[envName];
  if (typeof multibase !== "string" || multibase.length === 0) fail(`${envName} is not set (an environment secret of the conformance-issuance environment)`);
  let seed;
  try {
    seed = decodePrivateKeyMultibase(multibase.trim());
  } catch (err) {
    fail(`${envName}: ${err.message}`);
  }
  const publicMultibase = encodePublicKeyMultibase(publicRawFromSeed(seed));
  const key = programKeys.keys.find((candidate) => candidate.purpose === purpose && candidate.publicKeyMultibase === publicMultibase);
  if (key === undefined) fail(`${envName}: its public half is not a committed "${purpose}" key in registry/keys/program-keys.json - refusing to sign`);
  return { seed, key, verificationMethod: `${ISSUER_DID}#${key.id}` };
}
const issuerKey = matchKey("K_ISSUER_PRIVATE", "issuer");
const statusKey = matchKey("K_STATUS_PRIVATE", "status");

// ── the entry: the claim being attested must match the inputs exactly ───────
const slug = args.slug;
if (!/^[a-z0-9-]{2,40}$/.test(slug)) fail(`--slug must match ^[a-z0-9-]{2,40}$ (got ${JSON.stringify(slug)})`);
const entryPath = rel("registry", "builders", `${slug}.json`);
let entry;
try {
  entry = JSON.parse(readFileSync(entryPath, "utf8"));
} catch (err) {
  fail(`registry/builders/${slug}.json: ${err.message}`);
}
const claim = entry.conformance;
if (claim === undefined) fail(`registry/builders/${slug}.json carries no conformance claim`);
if (claim.status !== "in-verification") {
  fail(`entry status is "${claim.status}" - issuance requires "in-verification" (the open submission is the claim being verified)`);
}
// Identity binding at the source: the credential is ABOUT this entry's
// project, so its subject id must be an identity URL the entry declares.
// The validator re-proves this on every build; refusing here keeps a
// mis-keyed workflow input from ever reaching the signer.
const entryIdentities = [entry.homepage, entry.repo].filter((u) => typeof u === "string");
if (!entryIdentities.includes(args["subject-id"])) {
  fail(`--subject-id must be the entry's homepage or repo (${entryIdentities.join(" or ")}), got ${JSON.stringify(args["subject-id"])}`);
}
const categories = args.categories === undefined || args.categories === "" ? undefined : args.categories.split(",").map((c) => c.trim()).filter(Boolean);
if (claim.level !== args.level) fail(`input level ${args.level} does not match the entry's claim (${claim.level})`);
if (claim.scope !== args.scope) fail(`input scope ${args.scope} does not match the entry's claim (${claim.scope})`);
const inputCategories = [...(categories ?? [])].sort().join(",");
const claimCategories = [...(claim.categories ?? [])].sort().join(",");
if (inputCategories !== claimCategories) {
  fail(`input categories (${inputCategories || "none"}) do not match the entry's claim (${claimCategories || "none"})`);
}

// ── build + sign the credential ─────────────────────────────────────────────
const validFrom = new Date().toISOString().replace(/\.\d{3}Z$/, "Z");
const allocationsPath = rel("registry", "credentials", "allocations.json");
const allocations = JSON.parse(readFileSync(allocationsPath, "utf8"));
const statusIndex = allocations.nextIndex;
if (statusIndex >= STATUS_LIST_BITS) fail(`status list is full (nextIndex ${statusIndex} >= ${STATUS_LIST_BITS})`);

let credential;
try {
  credential = buildCredential({
    subjectId: args["subject-id"],
    implementation: {
      name: args["impl-name"],
      version: args["impl-version"],
      repo: args["impl-repo"] ?? entry.repo,
      digest: { gitCommit: args["git-commit"] },
    },
    level: args.level,
    scope: args.scope,
    categories,
    packageVersion: args["package-version"],
    statusIndex,
    validFrom,
  });
} catch (err) {
  fail(err.message);
}
if (claim.suiteVersion !== credential.credentialSubject.suite.suiteVersion) {
  fail(`the entry's claimed suiteVersion (${claim.suiteVersion}) does not match the pinned suite (${credential.credentialSubject.suite.suiteVersion})`);
}
const credentialPath = rel("registry", "credentials", `${credential.id.slice("urn:kya:conf:".length)}.json`);
try {
  readFileSync(credentialPath);
  fail(`credential ${credential.id} is already committed - the deterministic id refuses duplicate issuance`);
} catch (err) {
  if (err.code !== "ENOENT") throw err;
}
const signed = signCredential(credential, issuerKey.seed, issuerKey.verificationMethod);
{
  const { ok, reason } = verifyCredential(signed, issuerKey.key.publicKeyMultibase);
  if (!ok) fail(`self-verification of the new credential failed (${reason}) - nothing written`);
}

// ── rebuild + re-sign both status lists (bits preserved) ────────────────────
const listFiles = {};
for (const purpose of STATUS_PURPOSES) {
  const path = rel("registry", "credentials", "status", `${purpose}-1.json`);
  let bytes;
  try {
    const existing = JSON.parse(readFileSync(path, "utf8"));
    const { ok, reason } = verifyStatusListAgainstCommittedKey(existing, programKeys);
    if (!ok) fail(`existing ${purpose} list proof does not verify (${reason}) - refusing to carry its bits forward`);
    bytes = decodeStatusList(existing.credentialSubject.encodedList);
  } catch (err) {
    if (err.code !== "ENOENT") throw err;
    bytes = new Uint8Array(STATUS_LIST_BYTES); // first issuance: all-zero list
  }
  const unsigned = buildStatusListCredential({ purpose, encodedList: encodeStatusList(bytes), validFrom });
  const signedList = signCredential(unsigned, statusKey.seed, statusKey.verificationMethod);
  const { ok, reason } = verifyCredential(signedList, statusKey.key.publicKeyMultibase);
  if (!ok) fail(`self-verification of the ${purpose} list failed (${reason}) - nothing written`);
  listFiles[path] = signedList;
}

// ── write everything, then let the build re-verify it all ───────────────────
mkdirSync(rel("registry", "credentials", "status"), { recursive: true });
writeFileSync(credentialPath, JSON.stringify(signed, null, 2) + "\n");
for (const [path, list] of Object.entries(listFiles)) writeFileSync(path, JSON.stringify(list, null, 2) + "\n");
allocations.allocations.push({ index: statusIndex, credentialId: credential.id, slug, allocatedAt: validFrom });
allocations.nextIndex = statusIndex + 1;
writeFileSync(allocationsPath, JSON.stringify(allocations, null, 2) + "\n");

const attestationUrl = `${CREDENTIALS_BASE}/${credential.id.slice("urn:kya:conf:".length)}.json`;
entry.conformance = {
  level: claim.level,
  scope: claim.scope,
  ...(claim.categories !== undefined ? { categories: claim.categories } : {}),
  suiteVersion: claim.suiteVersion,
  status: "verified",
  attestationUrl,
  ...(claim.evidenceUrl !== undefined ? { evidenceUrl: claim.evidenceUrl } : {}),
};
writeFileSync(entryPath, JSON.stringify(entry, null, 2) + "\n");

// The site build is the final gate: it re-validates the registry, verifies
// the new credential and lists cryptographically, regenerates the badge
// allowlist, and refuses on any failure - in which case this exits non-zero
// and the workflow never opens a PR.
const build = spawnSync(process.execPath, [join(repoRoot, "site", "build-pages.mjs")], { stdio: "inherit" });
if (build.status !== 0) fail("the site build refused the issued artifacts - see errors above; nothing should be committed");

const realId32 = credential.id.slice("urn:kya:conf:".length);
const summary = {
  slug,
  credentialId: credential.id,
  id32: realId32,
  id8: realId32.slice(0, 8),
  attestationUrl,
  statusIndex,
  claim: `${claim.level} ${claim.scope}${claim.categories ? ` (${claim.categories.join(", ")})` : ""}`,
  gitCommit: args["git-commit"],
  verdictUrl: args["verdict-url"],
  validFrom,
};
if (args.summary) writeFileSync(args.summary, JSON.stringify(summary, null, 2) + "\n");
if (args["pr-body"]) {
  writeFileSync(
    args["pr-body"],
    [
      `## Issuance record: ${slug}`,
      "",
      `Signed under the \`conformance-issuance\` protected environment (reviewer approval of the workflow run is the human act; this PR is the auditable record; merging deploys).`,
      "",
      `| field | value |`,
      `| --- | --- |`,
      `| credential | \`${credential.id}\` |`,
      `| claim | ${summary.claim} |`,
      `| subject | ${args["subject-id"]} |`,
      `| implementation | ${args["impl-name"]}@${args["impl-version"]} |`,
      `| code digest | \`${args["git-commit"]}\` |`,
      `| suite | ${credential.credentialSubject.suite.suiteVersion} (${credential.credentialSubject.suite.vectorCount} vectors) |`,
      `| status index | ${statusIndex} (revocation-1 + suspension-1) |`,
      `| attestation URL | ${attestationUrl} (live after merge) |`,
      "",
      `Verdict this issuance executes: ${args["verdict-url"]}`,
      "",
      `Verify locally: \`node scripts/verify-credential.mjs --offline registry/credentials/${realId32}.json\``,
    ].join("\n") + "\n",
  );
}
console.log(JSON.stringify(summary, null, 2));
